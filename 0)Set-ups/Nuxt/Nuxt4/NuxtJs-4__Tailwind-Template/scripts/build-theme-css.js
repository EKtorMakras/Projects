/**
 * =========================================================
 * TAILWIND V4 THEME CSS GENERATOR
 *
 * Generates tokens.css with @theme directive from tokens.js
 * No more JavaScript config needed - everything is CSS-based.
 * =========================================================
 */

import { writeFileSync } from "fs";
import { fileURLToPath } from "url";
import { dirname, resolve } from "path";
import tokens from "../app/design-system/tokens.js";
import { hexToOklch } from "./helpers/color-utils.js";
import {
    generateBaseThemeCss,
    generateThemeOverrides,
    generateOpacityCss,
} from "./helpers/theme-builder.js";
import { generateSourceDirectives } from "./generate-safelist.js";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const OUTPUT_PATH = resolve(__dirname, "../app/assets/css/tokens.css");

/**
 * Generates complete theme CSS file
 */
function generateThemeFile() {
    const { colors, opacities } = tokens;

    let content = "";

    // Header
    content += `/**
 * =========================================================
 * 🚨 DO NOT MODIFY THIS FILE
 * This file is auto-generated by build-theme-css.js
 * Modify app/design-system/tokens.js instead.
 * =========================================================
 */

`;

    // Import Tailwind
    content += '@import "tailwindcss";\n\n';

    // Add @source inline directives
    content += generateSourceDirectives();

    // Base theme
    content += `/* ========================================
   BASE THEME (Light Mode Default)
   ======================================== */

@theme {
`;

    content += `    /* Base Color Palette (with shades) */
`;
    content += generateBaseThemeCss(colors);

    // Add light theme semantic colors as defaults in @theme (for Tailwind utilities)
    const lightTheme = colors.themes.light;
    const { palette: _lp, flat: _lf, ...lightSemanticTokens } = lightTheme;
    if (Object.keys(lightSemanticTokens).length > 0) {
        content += `    /* Semantic Colors (Light Theme Defaults) */
`;
        for (const [key, hex] of Object.entries(lightSemanticTokens)) {
            const comment = key.endsWith("-fg") ? "" : ` /* ${hex} */`;
            content += `    --color-${key}: ${hexToOklch(hex)};${comment}\n`;
        }
        content += "\n";
    }

    // Opacities
    if (opacities) {
        content += `    /* Opacity Values */
`;
        content += generateOpacityCss(opacities);
    }

    content += `}

`;

    // ALL themes (including light) get their own :root[data-theme="..."] section
    for (const [themeName, themeTokens] of Object.entries(colors.themes)) {
        content += `/* ========================================
   ${themeName.toUpperCase()} THEME
   ======================================== */

:root[data-theme="${themeName}"] {
`;
        content += generateThemeOverrides(colors, themeTokens);
        content += `}

`;
    }

    return content;
}

/**
 * Main execution
 */
function main() {
    console.log("🎨 Generating Tailwind v4 theme CSS...\n");

    const cssContent = generateThemeFile();
    writeFileSync(OUTPUT_PATH, cssContent, "utf-8");

    console.log("✅ tokens.css generated successfully");
    console.log(`   Output: ${OUTPUT_PATH}\n`);
}

main();
